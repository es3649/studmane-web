  <h3 id="crab">83: Crab Risotto</h3>
  <p>Makes 5-6 servings</p>
  <h4>Ingredients</h4>
  <ul>
    <li>1 lb crab meat or imitation crab (or 8 oz crab + 8 oz small cooked shrimp)</li>
    <li>3-4 stalks celery, chopped</li>
    <li>Green bell pepper, chopped</li>
    <li>1 onion, chopped</li>
    <li>4-5 cloves garlic, minced</li>

    <li>4 Tbs + 2 Tbs + 2 Tbs unsalted butter</li>
    <li>6 c water</li>
    <li>1 Tbs Tabasco Sauce</li>

    <li>1.5 c uncooked rice</li>

    <li>2 tsp Salt</li>
    <li>1 tsp Smoked Paprika</li>
    <li>1 tsp Oregano</li>
    <li>1/2 tsp Celery seed</li>
    <li>1/2 tsp Garlic powder</li>
    <li>1/4 tsp Thyme</li>
    <li>1/4 tsp Black Pepper</li>
    <li>1/4 tsp Cayenne Pepper</li>
  </ul>

  <h4>Directions</h4>
  <ol>
    <li>
      Prepare a broth by combining water, 4 Tbs butter, and Tabasco. Bring to a boil, then reduce
      heat to simmer
    </li>
    <li>In a large pot, heat 2 Tbs butter over medium-high heat, and sauté vegetables</li>
    <li>
      In another pan, melt 2 Tbs butter, add garlic and sauté until fragrant, about 30 seconds. Add
      meat and sauté for about 3 minutes
    </li>
    <li>
      Add the meat and rice to the vegetables, then follow the
      <a href="#risotto-method">Risotto method</a> using the broth prepared in step 1
    </li>
    <li>When the rice is nearly finished, add the spices</li>
    <li>Serve with Tabasco</li>
  </ol>

