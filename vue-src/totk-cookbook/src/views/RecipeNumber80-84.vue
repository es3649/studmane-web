  <h2 id="risotto-method">The Risotto Method</h2>
  <ol>
    <li>Base ingredients are prepared as desired and placed into a large pot.</li>
    <li>
      Uncooked rice is added to the pot, then hot broth or another boiling liquid is poured over the
      rice and base ingredients until the mixture is just barely covered with the liquid. The
      remaining liquid should be kept at a simmer while the risotto continues cooking.
    </li>
    <li>
      The risotto pot should be checked often, and more liquid added as needed to keep the rice and
      base ingredients barely covered. Stir occasionally.
    </li>
    <li>Continue this process until the rice is fully cooked, about 30 minutes.</li>
    <li>Once the rice is nearly cooked, spices and other mix-ins are added.</li>
  </ol>
